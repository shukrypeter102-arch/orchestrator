// Use TARGET_BUILD_VARIANT to determine if we are on a debug build or not.
// "userdebug" is a debug build, "user" is a release build. This statement is
// evaluated at compile time, so it will be compiled into our binary.
pub const USERDEBUG: bool = !const_str::equal!(env!("TARGET_BUILD_VARIANT"), "user");

const LOG_LEVEL: LevelFilter = if USERDEBUG {
    LevelFilter::Debug
} else {
    LevelFilter::Info
};

pub fn setup_logging(tag: &'static str) {
    android_logger::init_once(
        android_logger::Config::default()
            .with_tag(tag)
            .with_max_level(LOG_LEVEL),
    );

    hzos_soft_error::init_once(
        hzos_soft_error::Config::default()
            .with_error_name(ErrorName::Memflow)
            .with_runtime_type(RuntimeType::Spawn)
            .with_mock(false),
    );

    // Redirect panic messages to logcat.
    panic::set_hook(Box::new(|panic_info| {
        error!("{}", panic_info);
    }));
}

